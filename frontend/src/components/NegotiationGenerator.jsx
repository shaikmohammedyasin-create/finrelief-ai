import React, { useState } from "react";
import { FiCheck, FiCopy, FiDownload, FiZap } from "react-icons/fi";

import { useToast } from "../context/ToastContext.jsx";
import { generateNegotiationLetter } from "../services/negotiationService.js";
import { extractErrorMessage } from "../services/api.js";
import Spinner from "./Loader.jsx";

const SOURCE_LABEL = {
  gemini: "Generated by Google Gemini",
  fallback: "Generated with rule-based fallback (AI temporarily unavailable)",
};

export default function NegotiationGenerator({ loans, initialLoanId }) {
  const toast = useToast();
  const [loanId, setLoanId] = useState(initialLoanId || loans?.[0]?.id || "");
  const [isGenerating, setIsGenerating] = useState(false);
  const [result, setResult] = useState(null);
  const [copied, setCopied] = useState(false);

  async function handleGenerate() {
    if (!loanId) {
      toast.error("Select a loan first.");
      return;
    }
    setIsGenerating(true);
    setResult(null);
    try {
      const data = await generateNegotiationLetter({ loanId });
      setResult(data);
    } catch (error) {
      toast.error(extractErrorMessage(error));
    } finally {
      setIsGenerating(false);
    }
  }

  function handleCopy() {
    navigator.clipboard.writeText(result.letter);
    setCopied(true);
    toast.success("Letter copied to clipboard.");
    setTimeout(() => setCopied(false), 2000);
  }

  function handleDownload() {
    const blob = new Blob([result.letter], { type: "text/plain" });
    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;
    link.download = `negotiation-letter-${result.lender_name.replace(/\s+/g, "_")}.txt`;
    document.body.appendChild(link);
    link.click();
    link.remove();
    URL.revokeObjectURL(url);
  }

  return (
    <div className="space-y-6">
      <div className="glass-card space-y-4 p-6">
        <div>
          <label className="field-label" htmlFor="loan-select">Select Loan</label>
          {loans && loans.length > 0 ? (
            <select id="loan-select" className="input-field" value={loanId} onChange={(e) => setLoanId(e.target.value)}>
              {loans.map((loan) => (
                <option key={loan.id} value={loan.id}>
                  {loan.lender_name} — ₹{loan.outstanding_amount.toLocaleString()} outstanding
                </option>
              ))}
            </select>
          ) : (
            <p className="text-sm text-ink-muted">Add a loan first to generate a negotiation letter.</p>
          )}
        </div>

        <button onClick={handleGenerate} disabled={isGenerating || !loanId} className="btn-primary w-full">
          {isGenerating ? <Spinner /> : <FiZap className="h-4 w-4" />}
          {isGenerating ? "Generating..." : "Generate Negotiation Letter"}
        </button>
      </div>

      {result && (
        <div className="glass-card animate-fade-in p-6">
          <div className="mb-4 flex flex-wrap items-center justify-between gap-2">
            <div>
              <p className="font-display font-semibold text-ink-primary">{result.lender_name}</p>
              <p className="mt-0.5 text-xs text-ink-muted">{SOURCE_LABEL[result.source] || result.source}</p>
            </div>
            <div className="flex gap-2">
              <button onClick={handleCopy} className="btn-secondary !px-3 !py-2 text-sm">
                {copied ? <FiCheck className="h-4 w-4 text-accent-mint" /> : <FiCopy className="h-4 w-4" />}
              </button>
              <button onClick={handleDownload} className="btn-secondary !px-3 !py-2 text-sm">
                <FiDownload className="h-4 w-4" />
              </button>
            </div>
          </div>
          <div className="rounded-lg border border-white/[0.06] bg-black/20 p-5">
            <pre className="whitespace-pre-wrap font-body text-sm leading-relaxed text-ink-primary">{result.letter}</pre>
          </div>
          <p className="mt-3 text-xs text-ink-muted">
            Proposed settlement: <span className="money text-ink-secondary">₹{result.settlement_amount.toLocaleString()}</span> ({result.settlement_percentage}%)
          </p>
        </div>
      )}
    </div>
  );
}
